export interface RepositoryBaselineReport {
  generatedAt: string;
  environment: { node: string; platform: string; arch: string };
  corpus: { records: number; distractors: number; topK: number };
  retrieval: {
    answerableQueries: number;
    unanswerableQueries: number;
    falsePositiveQueries: number;
    precisionAt5: number;
    recallAt5: number;
    meanReciprocalRank: number;
    staleLeaks: number;
    answerableCoverage: number;
    incorrectAnswerRate: number;
    noAnswerFalsePositiveRate: number;
    maximumPrecisionAt5: number;
    precisionGateValid: boolean;
  };
  latencyMs: { samples: number; p50: number; p95: number };
  context: { estimatedTokens: number; limit: number; withinLimit: boolean };
  cases: Array<{ query: string; expectedId: string | null; returnedIds: string[] }>;
  passed: boolean;
}

function percentile(values: number[], fraction: number): number {
  const sorted = [...values].sort((a, b) => a - b);
  return sorted[Math.min(sorted.length - 1, Math.ceil(sorted.length * fraction) - 1)] ?? 0;
}

export function runRepositoryBaseline(corpusSize = CORPUS_SIZE, expanded = false): RepositoryBaselineReport {
  if (!Number.isSafeInteger(corpusSize) || corpusSize < REPOSITORY_FACTS.length + 1) throw new Error('Invalid corpus size');
  const workspace = fs.mkdtempSync(path.join(os.tmpdir(), 'hm-repo-baseline-'));
  try {
    const memoryDir = path.join(workspace, '.hypersabmemory');
    fs.mkdirSync(memoryDir, { recursive: true });
    const distractors: MemoryRecord[] = Array.from({ length: corpusSize - REPOSITORY_FACTS.length - 1 }, (_, index) => ({
      id: `noise-${index}`,
      category: 'general',
      content: `Unrelated deployment fixture ${index} tracks an isolated service route and release note.`,
      timestamp: '2026-10-22T00:00:00.000Z',
      status: 'active'
    }));
    const records: MemoryRecord[] = [
      ...REPOSITORY_FACTS.map((fact) => ({
        id: fact.id,
        category: 'architecture' as const,
        content: fact.content,
        artifacts: fact.artifacts,
        timestamp: '2026-10-22T00:00:00.000Z',
        status: 'active' as const
      })),
      {
        id: 'stale-storage-fact',
        category: 'bug',
        content: 'Old superseded stale storage fact from the previous project engine.',
        timestamp: '2026-10-21T00:00:00.000Z',
        status: 'superseded'
      },
      ...distractors
    ];
    fs.writeFileSync(path.join(memoryDir, 'memory_store.json'), JSON.stringify(records, null, 2), 'utf8');

    const memory = new TemporalMemoryEngine(workspace);
    const hybrid = new HybridSearchEngine(workspace, memory);
    const previousQueries = [...QUERIES, ...EXTRA_QUERIES];
    const queries = expanded ? [
      ...previousQueries.filter(({ expectedId }) => expectedId !== null).slice(0, 20),
      ...previousQueries.filter(({ expectedId }) => expectedId === null),
      ...MISSING_QUERIES
    ] : QUERIES;
    const cases = queries.map(({ query, expectedId }) => ({
      query,
      expectedId,
      returnedIds: hybrid.searchRecords(query, TOP_K).map(({ id }) => id)
    }));
    const answerable = cases.filter(({ expectedId }) => expectedId !== null);
    let relevantRetrieved = 0;
    let precisionSum = 0;
    let reciprocalRankSum = 0;
    for (const testCase of answerable) {
      const relevant = testCase.returnedIds.filter((id) => id === testCase.expectedId).length;
      relevantRetrieved += relevant;
      precisionSum += relevant / TOP_K;
      const rank = testCase.returnedIds.indexOf(testCase.expectedId!);
      if (rank >= 0) reciprocalRankSum += 1 / (rank + 1);
    }

    const staleLeaks = cases.reduce((count, testCase) =>
      count + testCase.returnedIds.filter((id) => id === 'stale-storage-fact').length, 0);
    const latencySamples: number[] = [];
    for (const { query } of queries) {
      hybrid.searchRecords(query, TOP_K);
      for (let iteration = 0; iteration < (expanded ? 5 : ITERATIONS_PER_QUERY); iteration++) {
        const start = performance.now();
        hybrid.searchRecords(query, TOP_K);
        latencySamples.push(performance.now() - start);
      }
    }

    const header = new ContextHarness(1500).generateHeader({
      workspaceName: 'HyperSABMemory',
      activeFile: 'src/memory/temporalMemory.ts',
      gitBranch: 'main',
      modifiedFiles: ['src/memory/sqliteStore.ts', 'src/hooks/autoCommit.ts'],
      memorySummary: `6 repository-grounded facts; ${distractors.length} irrelevant records`,
      contextBlock: '[CONTEXT BLOCK]\n[decision] Preserve the JSON store and 1500-token header limit.',
      structuralGraphSummary: 'Repository graph source: graph.json'
    });
    const estimatedTokens = TokenCompressor.estimateTokens(header);

    const precisionAt5 = precisionSum / answerable.length;
    const recallAt5 = relevantRetrieved / answerable.length;
    const withinLimit = estimatedTokens <= 1500;
    const falsePositiveQueries = cases.filter(({ expectedId, returnedIds }) => expectedId === null && returnedIds.length > 0).length;
    const unanswerableQueries = cases.length - answerable.length;
    const maximumPrecisionAt5 = 1 / TOP_K;

    return {
      generatedAt: new Date().toISOString(),
      environment: { node: process.version, platform: process.platform, arch: process.arch },
      corpus: { records: records.length, distractors: distractors.length, topK: TOP_K },
      retrieval: {
        answerableQueries: answerable.length,
        unanswerableQueries,
        falsePositiveQueries,
        precisionAt5,
        recallAt5,
        meanReciprocalRank: reciprocalRankSum / answerable.length,
        staleLeaks,
        answerableCoverage: answerable.filter(({ returnedIds }) => returnedIds.length > 0).length / answerable.length,
        incorrectAnswerRate: cases.filter(({ expectedId, returnedIds }) => returnedIds.length > 0 && (expectedId === null || returnedIds[0] !== expectedId)).length / cases.length,
        noAnswerFalsePositiveRate: falsePositiveQueries / unanswerableQueries,
        maximumPrecisionAt5,
        precisionGateValid: maximumPrecisionAt5 >= 0.5
      },
      latencyMs: {
        samples: latencySamples.length,
        p50: percentile(latencySamples, 0.5),
        p95: percentile(latencySamples, 0.95)
      },
      context: { estimatedTokens, limit: 1500, withinLimit },
      cases,
      passed: expanded ? recallAt5 >= 0.85 && precisionAt5 >= 0.5 && maximumPrecisionAt5 >= 0.5 && falsePositiveQueries <= 1 && staleLeaks === 0 && withinLimit : recallAt5 >= 0.8 && staleLeaks === 0 && withinLimit
    };
  } finally {
    fs.rmSync(workspace, { recursive: true, force: true });
  }
}
